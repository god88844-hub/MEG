//! Deterministic workspace build and mechanical artifact verification.

use anyhow::{bail, Result};
use std::path::Path;

/// Build-goal detection (website / app / game / site / tool / api).
pub fn is_build_goal(goal: &str) -> bool {
    let g = goal.to_lowercase();
    [
        "website",
        "web app",
        "webapp",
        "game",
        "site",
        "landing page",
        "app ",
    ]
    .iter()
    .any(|k| g.contains(k))
        || (g.contains("build") && g.contains("page"))
}

pub fn is_explicit_2d(goal: &str) -> bool {
    let g = goal.to_lowercase();
    (g.contains("2d") || g.contains("two-dimensional")) && !g.contains("3d")
}

fn slug_of(goal: &str) -> String {
    let s: String = goal
        .to_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect();
    let trimmed = s.trim_matches('-').to_string();
    let collapsed: String = trimmed
        .split('-')
        .filter(|p| !p.is_empty())
        .collect::<Vec<_>>()
        .join("-");
    collapsed.chars().take(60).collect()
}

/// Mechanical verification (eval-ladder stage 1, Rust parity): spec tokens,
/// artifact presence. Returns (passed, details).
pub fn mechanical_check(goal: &str, workspace: &Path, artifacts: &[String]) -> (bool, Vec<String>) {
    let mut details = Vec::new();
    let mut passed = true;
    let g = goal.to_lowercase();

    for artifact in artifacts {
        let path = workspace.join(artifact);
        if !path.is_file() {
            passed = false;
            details.push(format!("{artifact}: missing"));
            continue;
        }
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        let lower = text.to_lowercase();
        // Spec tokens: 2d requested -> canvas present, depth markers absent.
        if is_explicit_2d(goal) && artifact.ends_with(".html") {
            let canvas = lower.contains("<canvas");
            let depth = ["three.js", "threejs", "webgl", "3d"]
                .iter()
                .any(|m| lower.contains(m));
            if !canvas {
                passed = false;
                details.push(format!("{artifact}: 2d requested but <canvas> absent"));
            }
            if depth {
                passed = false;
                details.push(format!(
                    "{artifact}: depth-rendering marker present but 2d requested"
                ));
            }
            details.push(format!(
                "{artifact}: canvas={} depth-leaks={}",
                if canvas { "yes" } else { "no" },
                if depth { "yes" } else { "no" }
            ));
        }
        // Every emitted HTML artifact must at least be non-trivial.
        if artifact.ends_with(".html") && text.len() < 200 {
            passed = false;
            details.push(format!("{artifact}: suspiciously small ({})", text.len()));
        }
        let _ = g;
    }
    (passed, details)
}

/// Deterministic flat 2D site builder. Returns surviving artifact paths
/// (relative to the workspace). Zero model tokens: pure rails, exactly the
/// pattern-pack doctrine (the 7B never writes boilerplate).
pub fn build_site(workspace: &Path, goal: &str) -> Result<Vec<String>> {
    if !is_build_goal(goal) {
        bail!("not a build goal");
    }
    let dir = workspace.join(slug_of(goal));
    std::fs::create_dir_all(&dir)?;

    let title = "MEG 2D Canvas Experience";
    let index = format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
<link rel="stylesheet" href="styles.css">
</head>
<body>
<main class="stage">
  <h1>{title}</h1>
  <p class="sub">Flat canvas rendering - generated by MEG deterministic rails.</p>
  <canvas id="scene" width="960" height="540"></canvas>
  <noscript>This experience requires JavaScript.</noscript>
</main>
<script src="app.js"></script>
</body>
</html>
"#
    );
    let app_js = r##"// MEG deterministic rails: flat 2D canvas animation (no depth pipeline).
const canvas = document.getElementById("scene");
const ctx = canvas.getContext("2d");
const stars = [];
for (let i = 0; i < 160; i++) {
  stars.push({
    x: Math.random() * canvas.width,
    y: Math.random() * canvas.height,
    r: Math.random() * 1.8 + 0.4,
    speed: Math.random() * 0.6 + 0.2,
  });
}
function tick() {
  ctx.fillStyle = "#04070f";
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = "#dfe9ff";
  for (const s of stars) {
    ctx.beginPath();
    ctx.arc(s.x, s.y, s.r, 0, Math.PI * 2);
    ctx.fill();
    s.y += s.speed;
    if (s.y > canvas.height) s.y = 0;
  }
  requestAnimationFrame(tick);
}
tick();
"##;
    let styles = r##"/* MEG deterministic rails */
* { margin: 0; padding: 0; box-sizing: border-box; }
body {
  background: #04070f;
  color: #dfe9ff;
  font-family: "Segoe UI", system-ui, sans-serif;
  display: grid;
  place-items: center;
  min-height: 100vh;
}
.stage { text-align: center; padding: 2rem; }
.stage h1 { letter-spacing: 0.08em; margin-bottom: 0.5rem; }
.stage .sub { color: #6b7a99; margin-bottom: 1.5rem; }
#scene {
  border: 1px solid #16233d;
  border-radius: 8px;
  max-width: 100%;
  height: auto;
}
"##;
    let readme = format!(
        "# {}\n\nGenerated by MEG deterministic rails (Rust core).\n\n\
         ## Run\n\nOpen `index.html` in a browser, or serve the folder:\n\n```\npython -m http.server 8123\n```\n",
        title
    );

    let artifacts = vec![
        ("index.html", index),
        ("app.js", app_js.into()),
        ("styles.css", styles.into()),
        ("README.md", readme),
    ];
    let mut surviving = Vec::new();
    for (name, content) in artifacts {
        let path = dir.join(name);
        std::fs::write(&path, content)?;
        surviving.push(format!("{}/{}", slug_of(goal), name));
    }
    Ok(surviving)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn build_goal_detection() {
        assert!(is_build_goal(
            "Create a 2d space themed website ready for shipping"
        ));
        assert!(is_build_goal("build a landing page"));
        assert!(!is_build_goal("fix the parser"));
    }

    #[test]
    fn site_has_canvas_and_no_depth_markers() {
        let ws = std::env::temp_dir().join(format!("meg-build-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&ws);
        let artifacts = build_site(&ws, "Create a 2d space themed website").unwrap();
        assert_eq!(artifacts.len(), 4);
        let (passed, details) =
            mechanical_check("Create a 2d space themed website", &ws, &artifacts);
        assert!(passed, "mechanical failed: {details:?}");
        let html = std::fs::read_to_string(ws.join(&artifacts[0])).unwrap();
        assert!(html.contains("<canvas"));
        assert!(!html.to_lowercase().contains("webgl"));
        assert!(!html.to_lowercase().contains("three."));
        let _ = std::fs::remove_dir_all(&ws);
    }

    #[test]
    fn mechanical_gate_rejects_depth_leak() {
        let ws = std::env::temp_dir().join(format!("meg-build-bad-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&ws);
        let dir = ws.join("leak");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("index.html"),
            "<canvas></canvas><script>THREE.WebGLRenderer()</script>",
        )
        .unwrap();
        let (passed, details) =
            mechanical_check("build a 2d site", &ws, &["leak/index.html".to_string()]);
        assert!(!passed);
        assert!(details.iter().any(|d| d.contains("depth-rendering marker")));
        let _ = std::fs::remove_dir_all(&ws);
    }

    #[test]
    fn slug_is_clean() {
        assert_eq!(
            slug_of("Create a 2d space themed website ready for shipping"),
            "create-a-2d-space-themed-website-ready-for-shipping"
        );
    }
}
